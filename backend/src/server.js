import 'dotenv/config';
import express from 'express';
import cors from 'cors';
import research from './routes/research.js';
import writing from './routes/writing.js';
const app = express();
app.use(cors({ origin: process.env.FRONTEND_ORIGIN || true }));
app.use(express.json({ limit: '1mb' }));
app.get('/api/health', (_req,res) => res.json({ ok: true, service: 'AI Editorial Workspace' }));
app.use('/api/research', research);
app.use('/api/writing', writing);
app.use((err,_req,res,_next) => { console.error(err); res.status(500).json({ error: 'Something went wrong. Please retry with a shorter input.' }); });
const port = process.env.PORT || 5000;
app.listen(port, () => console.log(`Editorial API listening on ${port}`));
